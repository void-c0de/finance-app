CREATE TABLE IF NOT EXISTS public.user_subscriptions (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  plan text NOT NULL DEFAULT 'standard' CHECK (plan IN ('standard', 'premium')),
  status text NOT NULL DEFAULT 'inactive' CHECK (status IN ('inactive', 'active', 'trial', 'expired', 'cancelled', 'granted')),
  source text NOT NULL DEFAULT 'none' CHECK (source IN ('none', 'coupon', 'admin', 'store', 'migration')),
  premium_started_at timestamptz,
  premium_expires_at timestamptz,
  permanent boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.premium_coupons (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL,
  duration_days integer,
  permanent boolean NOT NULL DEFAULT false,
  max_uses integer,
  expires_at timestamptz,
  active boolean NOT NULL DEFAULT true,
  one_per_account boolean NOT NULL DEFAULT true,
  note text,
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT premium_coupons_code_format CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{3,31}$'),
  CONSTRAINT premium_coupons_duration CHECK ((permanent AND duration_days IS NULL) OR (NOT permanent AND duration_days BETWEEN 1 AND 3650)),
  CONSTRAINT premium_coupons_max_uses CHECK (max_uses IS NULL OR max_uses > 0)
);

