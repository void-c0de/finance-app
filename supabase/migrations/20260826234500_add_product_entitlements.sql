CREATE OR REPLACE FUNCTION public.get_my_product_access()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_role text;
  v_sub public.user_subscriptions%ROWTYPE;
  v_premium boolean;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  SELECT role INTO v_role FROM public.profiles WHERE id = v_user_id;
  SELECT * INTO v_sub FROM public.user_subscriptions WHERE user_id = v_user_id;
  v_premium := v_role = 'superuser' OR (
    v_sub.plan = 'premium' AND v_sub.status IN ('active', 'trial', 'granted')
    AND (v_sub.permanent OR v_sub.premium_expires_at > now())
  );
  RETURN jsonb_build_object(
    'role', coalesce(v_role, 'user'),
    'plan', CASE WHEN v_premium THEN 'premium' ELSE 'standard' END,
    'isPremium', v_premium,
    'isSuperuser', v_role = 'superuser',
    'premiumExpiresAt', CASE WHEN v_role = 'superuser' OR v_sub.permanent THEN NULL ELSE v_sub.premium_expires_at END,
    'source', CASE WHEN v_role = 'superuser' THEN 'superuser' ELSE coalesce(v_sub.source, 'none') END
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.redeem_premium_coupon(p_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_coupon public.premium_coupons%ROWTYPE;
  v_existing_until timestamptz;
  v_from timestamptz;
  v_until timestamptz;
  v_uses bigint;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  SELECT * INTO v_coupon FROM public.premium_coupons
  WHERE code = upper(trim(p_code)) FOR UPDATE;
  IF NOT FOUND OR NOT v_coupon.active THEN RAISE EXCEPTION 'coupon_invalid'; END IF;
  IF v_coupon.expires_at IS NOT NULL AND v_coupon.expires_at <= now() THEN RAISE EXCEPTION 'coupon_expired'; END IF;
  IF v_coupon.one_per_account AND EXISTS (
    SELECT 1 FROM public.coupon_redemptions WHERE coupon_id = v_coupon.id AND user_id = v_user_id
  ) THEN RAISE EXCEPTION 'coupon_already_redeemed'; END IF;
  SELECT count(*) INTO v_uses FROM public.coupon_redemptions WHERE coupon_id = v_coupon.id;
  IF v_coupon.max_uses IS NOT NULL AND v_uses >= v_coupon.max_uses THEN RAISE EXCEPTION 'coupon_limit_reached'; END IF;
  SELECT premium_expires_at INTO v_existing_until FROM public.user_subscriptions
  WHERE user_id = v_user_id AND plan = 'premium' AND status IN ('active', 'trial', 'granted');
  v_from := greatest(now(), coalesce(v_existing_until, now()));
  v_until := CASE WHEN v_coupon.permanent THEN NULL ELSE v_from + make_interval(days => v_coupon.duration_days) END;
  INSERT INTO public.coupon_redemptions(coupon_id, user_id, premium_from, premium_until)
  VALUES (v_coupon.id, v_user_id, v_from, v_until);
  INSERT INTO public.user_subscriptions(user_id, plan, status, source, premium_started_at, premium_expires_at, permanent)
  VALUES (v_user_id, 'premium', 'active', 'coupon', now(), v_until, v_coupon.permanent)
  ON CONFLICT (user_id) DO UPDATE SET
    plan = 'premium', status = 'active', source = 'coupon',
    premium_started_at = coalesce(user_subscriptions.premium_started_at, now()),
    premium_expires_at = CASE WHEN user_subscriptions.permanent THEN user_subscriptions.premium_expires_at ELSE excluded.premium_expires_at END,
    permanent = user_subscriptions.permanent OR excluded.permanent;
  RETURN public.get_my_product_access();
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_create_coupon(
  p_code text, p_duration_days integer DEFAULT 30, p_max_uses integer DEFAULT NULL,
  p_expires_at timestamptz DEFAULT NULL, p_note text DEFAULT NULL, p_permanent boolean DEFAULT false
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_id uuid;
BEGIN
  IF NOT public.is_superuser() THEN RAISE EXCEPTION 'admin_required'; END IF;
  INSERT INTO public.premium_coupons(code, duration_days, max_uses, expires_at, note, permanent, created_by)
  VALUES (upper(trim(p_code)), CASE WHEN p_permanent THEN NULL ELSE p_duration_days END, p_max_uses, p_expires_at, nullif(trim(p_note), ''), p_permanent, auth.uid())
  RETURNING id INTO v_id;
  INSERT INTO public.admin_audit_log(actor_user_id, action, entity_id, metadata)
  VALUES (auth.uid(), 'coupon.created', v_id::text, jsonb_build_object('code', upper(trim(p_code)), 'durationDays', p_duration_days, 'maxUses', p_max_uses, 'permanent', p_permanent));
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_coupon_active(p_coupon_id uuid, p_active boolean)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_superuser() THEN RAISE EXCEPTION 'admin_required'; END IF;
  UPDATE public.premium_coupons SET active = p_active WHERE id = p_coupon_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'coupon_not_found'; END IF;
  INSERT INTO public.admin_audit_log(actor_user_id, action, entity_id, metadata)
  VALUES (auth.uid(), CASE WHEN p_active THEN 'coupon.enabled' ELSE 'coupon.disabled' END, p_coupon_id::text, '{}'::jsonb);
END;
$$;

